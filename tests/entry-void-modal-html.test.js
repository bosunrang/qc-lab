'use strict';
const assert=require('node:assert/strict');
const {spawnSync}=require('node:child_process');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const source=pathToFileURL(path.join(__dirname,'..','src','presentation','entry','entry-void-modal-html.ts')).href;
const program=`import {entryVoidModalHtml} from ${JSON.stringify(source)}; console.log(entryVoidModalHtml({pointInfoHtml:'Ngày 14/08 · Mức 1',closeButtonHtml:'<button>×</button>',closeFooterButtonHtml:'<button>Đóng</button>',confirmButtonHtml:'<button>Xác nhận</button>'}));`;

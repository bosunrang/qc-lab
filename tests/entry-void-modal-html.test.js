assert.equal(result.status,0,result.stderr||'không thể chạy Entry void modal TypeScript');
assert.match(result.stdout,/<h3>Hủy điểm QC<\/h3>/) && assert.match(result.stdout,/id="voidKindInput"/) && assert.match(result.stdout,/id="voidOpenNce"/) && assert.match(result.stdout,/id="voidReasonInput"/) && assert.match(result.stdout,/Ngày 14\/08/) && assert.match(result.stdout,/<button>Xác nhận<\/button>/);

async function assertAlignedPanels(page) {
  await page.waitForFunction(() => {
    const left = document.querySelector('.eqa-corrective-list')?.getBoundingClientRect();
    const right = document.querySelector('.eqa-corrective-inspector')?.getBoundingClientRect();
    return left && right && Math.abs(left.top - right.top) < 1 && Math.abs(left.bottom - right.bottom) < 1;
  });
}


import assert from 'node:assert/strict';
import test from 'node:test';
import { _electron } from 'playwright-core';
import { generateKeyPairSync } from 'node:crypto';
import { mkdtempSync, cpSync, writeFileSync, readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import os from 'node:os';
const root = fileURLToPath(new URL('../..', import.meta.url));
const require = createRequire(import.meta.url);
const { validateLicenseToken } = require('../../app-dist/main/licensing/license-token.js');

test('công cụ cấp key: chọn khoá, tạo, sao chép, lưu và đổi thông tin bỏ mã cũ; mở lại nhớ khoá', { timeout: 120_000 }, async () => {
  const built = spawnSync(process.execPath, ['app/scripts/build-license-issuer.cjs'], { cwd: root, encoding: 'utf8' });
  assert.equal(built.status, 0, built.stderr);
  const dir = mkdtempSync(path.join(os.tmpdir(), 'qclab-issuer-gui-'));
  const fixture = path.join(dir, 'app'), profile = path.join(dir, 'profile'), privatePath = path.join(dir, 'issuer.private.pem');
  cpSync(path.join(root, '.cache/license-issuer'), fixture, { recursive: true });
  // Cặp khoá chỉ thuộc bài kiểm thử; không đọc/thay khoá thật của bên cấp.
  const keys = generateKeyPairSync('ed25519');
  const publicKey = keys.publicKey.export({ type: 'spki', format: 'pem' });
  writeFileSync(privatePath, keys.privateKey.export({ type: 'pkcs8', format: 'pem' }));
  writeFileSync(path.join(fixture, 'public-key.json'), JSON.stringify({ algorithm: 'Ed25519', publicKey }));
  const start = () => _electron.launch({ args: [fixture], cwd: root, env: { ...process.env, QCLAB_ISSUER_TEST_USER_DATA: profile } });
  let app = await start();
  try {
    const page = await app.firstWindow(); page.setDefaultTimeout(15_000);
    const errors = []; page.on('pageerror', (error) => errors.push(error.message));
    page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()); });
    await page.getByText('Không đọc được khoá bí mật. Hãy chọn lại tệp khoá cấp phép (.pem).', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: 'Tạo mã kích hoạt', exact: true }).isDisabled(), true);
    await app.evaluate(({ dialog }, privatePath) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [privatePath] }); }, privatePath);
    await page.getByRole('button', { name: 'Chọn khoá…', exact: true }).click();
    await page.getByText('Khoá cấp phép đã sẵn sàng', { exact: true }).waitFor();
    await page.locator('#machine-code').fill('sai mã máy');
    await page.locator('#customer').fill('Đơn vị thử nghiệm');
    await page.getByRole('button', { name: 'Tạo mã kích hoạt', exact: true }).click();
    await page.getByRole('alert').getByText(/Mã máy không đúng/).waitFor();
    const machine = 'QC-01234567-89ABCDEF-01234567-89ABCDEF';
    await page.locator('#machine-code').fill(machine.toLowerCase());
    await page.getByRole('button', { name: 'Tạo mã kích hoạt', exact: true }).click();
    await page.getByText('Đơn vị thử nghiệm · Vĩnh viễn', { exact: true }).waitFor();
    const code = await page.locator('#activation-code').inputValue();
    assert.equal(validateLicenseToken(code, publicKey, machine).ok, true);
    assert.equal(validateLicenseToken(code, publicKey, machine).claims.expiresAt, null);
    const preferences = readFileSync(path.join(profile, 'issuer-settings.json'), 'utf8');
    assert.equal(JSON.parse(preferences).keyPath, privatePath);
    assert.ok(!preferences.includes('PRIVATE KEY'));
    await page.getByRole('button', { name: 'Sao chép mã', exact: true }).click();
    await page.getByText('Đã sao chép mã kích hoạt.', { exact: true }).waitFor();
    assert.equal(await app.evaluate(({ clipboard }) => clipboard.readText()), code);
    const output = path.join(dir, 'ma-kich-hoat.txt');
    await app.evaluate(({ dialog }, filePath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath }); }, output);
    await page.getByRole('button', { name: 'Lưu tệp .txt', exact: true }).click();
    await page.getByText(`Đã lưu: ${output}`, { exact: true }).waitFor();
    assert.equal(readFileSync(output, 'utf8').trim(), code);
    await page.getByRole('button', { name: 'Lưu tệp .txt', exact: true }).click();
    await page.getByRole('alert').getByText(/Tệp đã tồn tại/).waitFor();
    assert.equal(readFileSync(output, 'utf8').trim(), code);
    await page.locator('#customer').fill('Đơn vị gia hạn');
    assert.equal(await page.locator('#activation-code').inputValue(), '');
    assert.equal(await page.getByRole('button', { name: 'Sao chép mã', exact: true }).isDisabled(), true);
    assert.equal((await page.evaluate(() => window.licenseIssuer.copy())).ok, false);
    await page.locator('#perpetual').uncheck();
    await page.locator('#expires-on').fill('31/12/2099');
    await page.locator('#expires-on').press('Enter');
    assert.equal(await page.locator('#expires-on').inputValue(), '31/12/2099');
    assert.equal(await page.locator('#activation-code').inputValue(), '', 'Enter trong ô ngày chỉ chốt ngày, không tự tạo mã');
    await page.locator('.datepick').click();
    await page.locator('#vnDatePicker').getByRole('button', { name: 'Tháng 12 2099', exact: true }).waitFor();
    assert.deepEqual(await page.locator('.vn-date-days span').allTextContents(), ['T2', 'T3', 'T4', 'T5', 'T6', 'T7', 'CN']);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#vnDatePicker').count(), 0);
    await page.locator('.datepick').click();
    await page.locator('#vnDatePicker').getByRole('button', { name: '30', exact: true }).click();
    assert.equal(await page.locator('#expires-on').inputValue(), '30/12/2099');
    await page.locator('#expires-on').fill('31/12/2099');
    await page.locator('#expires-on').press('Enter');
    await page.locator('#customer').click();
    await page.keyboard.press('Shift+Tab');
    const focus = await page.locator('#machine-code').evaluate((element) => {
      const css = getComputedStyle(element), root = getComputedStyle(document.documentElement);
      return { keyboard: element.matches(':focus-visible'), ring: css.outlineWidth, expected: root.getPropertyValue('--focus-ring-width').trim(), offset: css.outlineOffset, expectedOffset: root.getPropertyValue('--focus-ring-offset-inset').trim() };
    });
    assert.equal(focus.keyboard, true); assert.equal(focus.ring, focus.expected); assert.equal(focus.offset, focus.expectedOffset);
    const controls = await page.evaluate(() => {
      const root = getComputedStyle(document.documentElement), input = document.querySelector('#customer'), button = document.querySelector('#generate');
      return { input: getComputedStyle(input).height, button: getComputedStyle(button).height, expected: root.getPropertyValue('--control-h').trim() };
    });
    assert.equal(controls.input, controls.expected); assert.equal(controls.button, controls.expected);
    await page.getByRole('button', { name: 'Tạo mã kích hoạt', exact: true }).click();
    await page.getByText('Đơn vị gia hạn · Hết hạn 31/12/2099', { exact: true }).waitFor();
    const renewed = await page.locator('#activation-code').inputValue();
    assert.equal(validateLicenseToken(renewed, publicKey, machine).claims.expiresAt, '2099-12-31T16:59:59.999Z');
    await page.locator('main').evaluate((element) => { element.scrollTop = 0; });
    await page.screenshot({ path: path.join(dir, 'license-issuer.png'), fullPage: true });
    await page.setViewportSize({ width: 800, height: 730 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
    assert.deepEqual(errors, []);
    await app.close();
    app = await start();
    const reopened = await app.firstWindow();
    await reopened.getByText('Khoá cấp phép đã sẵn sàng', { exact: true }).waitFor();
    assert.equal(await reopened.locator('#activation-code').inputValue(), '', 'không lưu key khách hàng vào profile công cụ');
    console.log(`Ảnh công cụ cấp key: ${path.join(dir, 'license-issuer.png')}`);
  } finally { await app.close(); }
});

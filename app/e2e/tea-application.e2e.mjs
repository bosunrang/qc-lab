import assert from 'node:assert/strict';
import test from 'node:test';
import path from 'node:path';
import { bootstrapAndLogin, launchApp, openPage } from './helpers.mjs';

test('hồ sơ TEa: lựa chọn trực quan, giữ nháp, lỗi theo mức và lưu đúng hai cách áp dụng', { timeout: 150_000 }, async () => {
  const { app, page, errors, userDataDir } = await launchApp();
  try {
    await bootstrapAndLogin(page);
    const people = await page.evaluate(async () => {
      const must = result => { if (!result.ok) throw new Error(result.error.message); return result.data; };
      const create = (username, name) => window.qcApi.createUser({ data: { username, name, password: 'mat-khau-tea-123', role: 'technician' } });
      const prepared = must(await create('tea_preparer', 'KTV kiểm tra'));
      const approved = must(await create('tea_reviewer', 'Trưởng PXN'));
      const inactive = must(await create('tea_inactive', 'Tài khoản ngừng dùng'));
      must(await window.qcApi.updateUser({ id: inactive.id, data: { name: inactive.name, role: inactive.role, active: false } }));
      return { prepared, approved, inactive };
    });
    await page.setViewportSize({ width: 1366, height: 1000 });
    await openPage(page, 'Cấu hình chung');
    await page.getByRole('button', { name: /^Bảng TEa tham chiếu/ }).click();
    await page.getByRole('textbox', { name: 'Tìm trong bảng TEa tham chiếu', exact: true }).fill('Sodium');
    const row = page.locator('.tea-ref-table tbody tr').filter({ hasText: 'Sodium (Na)' });
    await row.getByRole('button', { name: 'Thêm hồ sơ', exact: true }).click();
    const modal = page.locator('.tea-lab-profile-modal');
    const section = modal.locator('.tea-form-section').filter({ hasText: 'Cách áp dụng TEa' });
    const common = modal.getByRole('radio', { name: 'TEa chung', exact: true });
    const perLevel = modal.getByRole('radio', { name: 'Theo từng mức QC', exact: true });
    const levelInput = level => modal.getByRole('spinbutton', { name: `TEa mức ${level}`, exact: true });
    const levelChoice = level => modal.getByRole('checkbox', { name: `Áp dụng TEa mức ${level}`, exact: true });
    const levelCard = level => modal.locator(`.tea-level-editor:has([data-field="levelTea:${level}"])`);
    assert.equal(await common.isChecked(), true);
    await modal.locator('#tea-profile-value').fill('15');
    assert.equal(await modal.locator('.tea-common-card input').inputValue(), '15');
    assert.equal(await modal.locator('.tea-common-preview').count(), 0);
    await section.screenshot({ path: path.join(userDataDir, 'tea-application-common.png') });
    await perLevel.check();
    assert.equal(await modal.locator('#tea-profile-value').count(), 0, 'theo mức không có ô TEa chung');
    assert.equal(await modal.locator('.tea-level-fallback').count(), 0);
    assert.equal(await levelChoice(1).isChecked(), true);
    assert.equal(await levelChoice(2).isChecked(), true);
    assert.equal(await levelInput(3).isDisabled(), true);
    await modal.getByRole('button', { name: 'Thêm hồ sơ TEa', exact: true }).click();
    const error = levelCard(1).locator('.field-error');
    await error.waitFor();
    assert.equal(await levelInput(1).getAttribute('aria-invalid'), 'true');
    assert.equal(await levelInput(1).evaluate(element => document.activeElement === element), true);
    const one = await levelCard(1).boundingBox();
    const two = await levelCard(2).boundingBox();
    assert.ok(Math.abs(one.y - two.y) < 1, 'lời nhắc lỗi không kéo lệch thẻ mức bên cạnh');
    await levelInput(1).fill('8.5');
    await error.waitFor({ state: 'detached' });
    await levelInput(2).fill('9.5');
    await levelChoice(3).check();
    await levelInput(3).fill('11');
    await levelChoice(3).uncheck();
    assert.equal(await levelInput(3).isDisabled(), true);
    await levelChoice(3).check();
    assert.equal(await levelInput(3).inputValue(), '11', 'bỏ chọn rồi chọn lại không mất nháp');
    await common.check();
    assert.equal(await modal.locator('#tea-profile-value').inputValue(), '15');
    await common.focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await perLevel.isChecked(), true, 'hai thẻ hỗ trợ điều hướng bằng bàn phím');
    assert.deepEqual(await Promise.all([1, 2, 3].map(level => levelInput(level).inputValue())), ['8.5', '9.5', '11']);
    await levelChoice(1).uncheck();
    await levelChoice(2).uncheck();
    assert.equal(await levelChoice(3).isDisabled(), true, 'giữ ít nhất một mức');
    await levelChoice(1).check();
    await levelChoice(2).check();
    await section.screenshot({ path: path.join(userDataDir, 'tea-application-levels.png') });
    await page.setViewportSize({ width: 560, height: 900 });
    assert.equal(await modal.evaluate(element => element.scrollWidth <= element.clientWidth), true, 'hộp hẹp không tràn ngang');
    await page.setViewportSize({ width: 1366, height: 1000 });
    await modal.locator('#tea-profile-source').selectOption('regulation');
    await modal.locator('#tea-profile-reference').fill('SOP-TEa-2026');
    await modal.locator('#tea-profile-reason').fill('Tiêu chí TEa đã được phòng xét nghiệm xem xét theo SOP.');
    await modal.getByRole('textbox', { name: 'Ngày hiệu lực', exact: true }).fill('01/01/2026');
    await modal.getByRole('textbox', { name: 'Ngày hiệu lực', exact: true }).blur();
    await modal.getByRole('textbox', { name: 'Ngày duyệt', exact: true }).fill('01/01/2026');
    await modal.getByRole('textbox', { name: 'Ngày duyệt', exact: true }).blur();
    const prepared = modal.getByRole('combobox', { name: 'Người chuẩn bị', exact: true });
    const approved = modal.getByRole('combobox', { name: 'Người duyệt', exact: true });
    await modal.getByRole('button', { name: 'Thêm hồ sơ TEa', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#tea-profile-prepared-by')?.getAttribute('aria-invalid') === 'true');
    assert.equal(await prepared.evaluate(element => document.activeElement === element), true, 'thiếu người chuẩn bị báo lỗi và focus đúng ô chọn');
    await prepared.selectOption(people.prepared.id);
    assert.match(await prepared.locator('option:checked').innerText(), /KTV kiểm tra.*@tea_preparer/);
    assert.equal(await prepared.locator(`option[value="${people.inactive.id}"]`).count(), 0, 'không chọn mới tài khoản ngừng hoạt động');
    await modal.getByRole('button', { name: 'Thêm hồ sơ TEa', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('#tea-profile-approved-by')?.getAttribute('aria-invalid') === 'true');
    await approved.selectOption(people.approved.id);
    await modal.getByRole('button', { name: 'Thêm hồ sơ TEa', exact: true }).click();
    await modal.waitFor({ state: 'detached' });
    const profile = await page.evaluate(async () => (await window.qcApi.listTeaRefs()).find(ref => ref.analyte_id === 'qclab-sodium'));
    assert.equal(profile.lab_prepared_by, 'KTV kiểm tra', 'lưu họ tên, không ghi id hoặc tên đăng nhập vào hồ sơ');
    assert.equal(JSON.parse(profile.sources_json).approvedBy, 'Trưởng PXN');
    assert.equal(profile.lab, null, 'theo mức không lưu TEa chung đã nhập ở chế độ khác');
    assert.deepEqual(profile.lab_level_defaults.map(({ level, tea }) => ({ level, tea })), [{ level: 1, tea: 8.5 }, { level: 2, tea: 9.5 }, { level: 3, tea: 11 }]);
    await row.getByRole('button', { name: 'Xem hồ sơ', exact: true }).click();
    assert.equal(await perLevel.isChecked(), true);
    assert.equal(await levelInput(3).inputValue(), '11');
    assert.equal(await modal.locator('#tea-profile-value').count(), 0);
    await common.check();
    await modal.locator('#tea-profile-value').fill('15');
    await modal.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click();
    await modal.waitFor({ state: 'detached' });
    const after = await page.evaluate(async id => (await window.qcApi.listTeaRefs()).find(ref => ref.id === id), profile.id);
    assert.equal(after.lab, 15);
    assert.deepEqual(after.lab_level_defaults, [], 'TEa chung không giữ mức riêng đang ẩn');
    await row.getByRole('button', { name: 'Xem hồ sơ', exact: true }).click();
    assert.equal(await common.isChecked(), true);
    assert.equal(await modal.locator('.tea-common-card input').inputValue(), '15');
    await page.evaluate(async people => {
      const a = await window.qcApi.updateUser({ id: people.prepared.id, data: { name: 'KTV kiểm tra đổi tên', role: people.prepared.role, active: true } });
      const b = await window.qcApi.updateUser({ id: people.approved.id, data: { name: people.approved.name, role: people.approved.role, active: false } });
      if (!a.ok || !b.ok) throw new Error('Chưa cập nhật được tài khoản kiểm thử.');
    }, people);
    await page.waitForFunction(({ preparedId, approvedId }) => {
      const a = document.querySelector(`#tea-profile-prepared-by option[value="${preparedId}"]`);
      const b = document.querySelector(`#tea-profile-approved-by option[value="${approvedId}"]`);
      return a?.textContent.includes('KTV kiểm tra đổi tên') && !b;
    }, { preparedId: people.prepared.id, approvedId: people.approved.id });
    assert.equal(await prepared.locator('option:checked').innerText(), 'KTV kiểm tra (đã lưu)', 'đổi tài khoản không viết lại tên lịch sử');
    assert.equal(await approved.locator('option:checked').innerText(), 'Trưởng PXN (đã lưu)', 'người duyệt cũ vẫn hiện sau khi ngừng tài khoản');
    await modal.locator('.tea-form-people').screenshot({ path: path.join(userDataDir, 'tea-profile-people.png') });
    await modal.getByRole('button', { name: 'Lưu thay đổi', exact: true }).click();
    await modal.waitFor({ state: 'detached' });
    const retained = await page.evaluate(async id => (await window.qcApi.listTeaRefs()).find(ref => ref.id === id), profile.id);
    assert.equal(retained.lab_prepared_by, 'KTV kiểm tra');
    assert.equal(JSON.parse(retained.sources_json).approvedBy, 'Trưởng PXN');
    assert.deepEqual(errors, []);
    console.log(`Ảnh kiểm tra cách áp dụng TEa: ${userDataDir}`);
  } catch (error) {
    await page.screenshot({ path: path.join(userDataDir, 'tea-application-failed.png') });
    console.log(`Ảnh khi kiểm tra chưa đạt: ${userDataDir}`);
    throw error;
  } finally { await app.close(); }
});
